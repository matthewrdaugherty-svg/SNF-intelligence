"""Profile every raw CSV: columns, row counts, CCN coverage, distinct keys.
Output: docs/PROFILE.md and db/profile.json. Reads only; no transformation."""
import duckdb, json, os, sys, glob
RAW = "/home/claude/snf-intel/raw"
con = duckdb.connect()
out = {}
md = ["# Raw file profile (auto-generated by scripts/01_profile.py)\n"]
for path in sorted(glob.glob(f"{RAW}/*.csv")):
    name = os.path.basename(path)
    try:
        rel = con.sql(f"SELECT * FROM read_csv('{path}', header=true, all_varchar=true, sample_size=-1)")
    except Exception as e:
        md.append(f"## {name}\nERROR: {e}\n"); continue
    cols = rel.columns
    n = con.execute(f"SELECT count(*) FROM read_csv('{path}', header=true, all_varchar=true, sample_size=-1)").fetchone()[0]
    ccn_col = next((c for c in cols if "CCN" in c.upper() or "PROVNUM" in c.upper() or c.upper()=="CMS CERTIFICATION NUMBER (CCN)"), None)
    info = {"rows": n, "ncols": len(cols), "columns": cols, "ccn_col": ccn_col}
    if ccn_col:
        q = f"""SELECT count(DISTINCT "{ccn_col}") d, count(*) FILTER (WHERE "{ccn_col}" IS NULL OR "{ccn_col}"='') nulls,
                min(length("{ccn_col}")) minlen, max(length("{ccn_col}")) maxlen
                FROM read_csv('{path}', header=true, all_varchar=true, sample_size=-1)"""
        d, nulls, mn, mx = con.execute(q).fetchone()
        info.update({"distinct_ccn": d, "null_ccn": nulls, "ccn_len_min": mn, "ccn_len_max": mx})
    out[name] = info
    md.append(f"## {name}\n- rows: {n:,}  cols: {len(cols)}  key col: `{ccn_col}`" +
              (f"  distinct CCN: {info['distinct_ccn']:,}  null CCN: {info['null_ccn']}  CCN len: {info['ccn_len_min']}-{info['ccn_len_max']}" if ccn_col else "") + "\n")
    md.append("- columns: " + "; ".join(cols) + "\n")
os.makedirs("/home/claude/snf-intel/docs", exist_ok=True)
open("/home/claude/snf-intel/docs/PROFILE.md","w").write("\n".join(md))
json.dump(out, open("/home/claude/snf-intel/db/profile.json","w"), indent=1)
for k,v in out.items():
    print(f"{v['rows']:>10,} rows {v['ncols']:>4} cols  CCN:{str(v.get('distinct_ccn','-')):>7}  {k}")
